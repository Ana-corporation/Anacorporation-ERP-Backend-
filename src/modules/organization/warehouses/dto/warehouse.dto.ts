import { z } from 'zod';
import { createZodDto } from 'nestjs-zod';
import { ListQuerySchema } from '@/common/dto/pagination.dto';
import {
  bigintIdSchema,
  optionalNullableBigintIdSchema,
  optionalPatchBigintIdSchema,
} from '@/common/zod/common.schemas';

/** Store categories first (they drive the code prefix); the last four are the original types. */
export const WarehouseLocationTypeSchema = z.enum([
  'RawMaterialStore',
  'SparesStore',
  'FinishedGoodsStore',
  'BoughtOutStore',
  'ElectricalStore',
  'GeneralStore',
  'OilStore',
  'Warehouse',
  'Store',
  'Godown',
  'Other',
]);

/**
 * warehouseCode / locationCode are generated by the backend; values sent by the client are dropped.
 * Prefix = storeCategory.codePrefix when storeCategoryId is sent, else from locationType.
 */
export const CreateWarehouseSchema = z.object({
  name: z.string().min(1).max(150),
  branchId: bigintIdSchema,
  storeCategoryId: optionalNullableBigintIdSchema,
  /** Omitted / empty → copied from the site's address */
  address: z.string().max(255).optional(),
  isActive: z.boolean().optional().default(true),
  locationType: WarehouseLocationTypeSchema.optional().default('Store'),
  binManagement: z.boolean().optional().default(false),
  isDefault: z.boolean().optional().default(false),
});

/**
 * The code never changes after creation (not in this schema, so it is dropped if sent).
 * branchId / storeCategoryId can change only while the location is unused (no bins, stock or documents).
 */
export const UpdateWarehouseSchema = z.object({
  name: z.string().min(1).max(150).optional(),
  branchId: bigintIdSchema.optional(),
  storeCategoryId: optionalPatchBigintIdSchema,
  address: z.string().max(255).optional().nullable(),
  isActive: z.boolean().optional(),
  locationType: WarehouseLocationTypeSchema.optional(),
  binManagement: z.boolean().optional(),
  isDefault: z.boolean().optional(),
});

/** List filters on top of the shared ones: site (siteId = branchId) and store category. */
export const WarehouseListQuerySchema = ListQuerySchema.extend({
  branchId: bigintIdSchema.optional(),
  siteId: bigintIdSchema.optional(),
  storeCategoryId: bigintIdSchema.optional(),
});

export class CreateWarehouseDto extends createZodDto(CreateWarehouseSchema) {}
export class WarehouseListQueryDto extends createZodDto(WarehouseListQuerySchema) {}
export class UpdateWarehouseDto extends createZodDto(UpdateWarehouseSchema) {}
